            self.assertEqual(info["pages"][0], "original-page")
            self.assertEqual(len(info["pages"]), 2)
            page = (self.out / (info["pages"][-1] + ".md")).read_text()
            self.assertIn("session_agent: " + rec["agent"], page)
            self.assertIn("session_id: session", page)
            self.assertIn("continues: original-page", page)
            self.assertIn("New conclusion (continued)", page)

