    def test_unsafe_privacy_yaml_is_refused_before_construction_or_model_calls(self):
        import yaml
        import source_links as L

        doubling = "base: &b0 {value: canary}\n" + "\n".join(
            f"b{i}: &b{i} {{<<: [*b{i - 1}, *b{i - 1}]}}" for i in range(1, 6))
        cases = (
            doubling,
            "base: &base {x: y}\ncopy: *base",
            "copy: {<<: {x: y}}",
            "copy: {!!merge '<<': {x: y}}",
            "loop: &loop [*loop]",
            "nested: " + "[" * (L.MAX_YAML_DEPTH + 1) + "x" + "]" * (L.MAX_YAML_DEPTH + 1),
            "wide: [" + ",".join(["x"] * 17) + "]",
            'padding: "' + "x" * L.MAX_FRONTMATTER_CHARS + '"',
            "sources: [unterminated",
        )
        for root in (self.out, self.bundle):
            page = root / "untrusted.md"
            for fm in cases:
                with self.subTest(root=root.name, case=fm[:40]), \
                        patch.object(L, "MAX_YAML_NODES", 16 if fm.startswith("wide:") else L.MAX_YAML_NODES), \
                        patch.object(yaml.SafeLoader, "construct_document",
                                     side_effect=AssertionError("unsafe YAML reached construction")) as construct:
                    page.write_text('---\n"no_llm": true\n' + fm + "\n---\nbody\n")
                    result, model = self.run_main(self.record())
                    self.assertIsInstance(result, str)
                    self.assertIn("cannot resolve privacy", result)
                    model.assert_not_called()
                    construct.assert_not_called()
                    self.assertFalse(list(self.done.iterdir()))
            page.unlink()

