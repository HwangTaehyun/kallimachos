class ContinuationTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory(prefix="kal-continuation-")
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        self.out = self.root / "distilled"
        self.done = self.out / ".done"
        self.done.mkdir(parents=True)
        self.bundle = self.root / "bundle"
        self.bundle.mkdir()
        for target in (patch.dict(os.environ, {"HOME": str(self.root), "KAL_VAULT": str(self.bundle)}, clear=True),
                       patch.object(D, "OUT", str(self.out)), patch.object(D, "DONE", str(self.done)),
                       patch.object(D, "REVIEW", str(self.out / "review.tsv")),
                       patch.object(I, "EXCLUDE", str(self.root / "exclude.txt")),
                       patch.object(D.ledger, "append")):
            target.start()
            self.addCleanup(target.stop)
        self.since = I.epoch("2020-01-01T00:00:00Z")
        self.secret = "ghp_" + "A" * 36

    def record(self, agent="claude", sid="session", **extra):
        return {"agent": agent, "session_id": sid, "project": "fixture", "text": "Collected transcript",
                "first_ts": "2020-01-01T00:00:00Z", "last_ts": "2020-01-02T00:00:00Z", "n_msg": 2, **extra}

    def page(self, path, *, agent="claude", sid="session", blocked=False, continues=None, published=False):
        provenance = f"sources:\n  - resource: {agent}-session://{sid}" if published else f"session_id: {sid}\nsession_agent: {agent}"
        text = f"---\ntitle: Human changed title\n{provenance}\n"
        if blocked:
            text += '"no_llm": true # reviewed\n'
        if continues:
            text += f"continues: {continues}\n"
        path.write_text(text + "---\nSaved conclusion.\n")

    def run_main(self, rec, answer="SKIP", restart=False):
        with patch.object(D, "corpus_records", return_value=([rec], [])), \
                patch.object(sys, "argv", ["distill_sessions.py", "--workers", "1"] + (["--restart"] if restart else [])), \
                patch.object(D, "call", return_value=answer) as model, contextlib.redirect_stdout(io.StringIO()):
            result = 0
            try:
                D._main_distill()
            except SystemExit as error:
                result = error.code
        return result, model

    def test_local_and_published_identity_carries_privacy_without_rewriting_public_pages(self):
        published = self.bundle / "renamed-public.md"
        self.page(published, blocked=True, published=True)
        self.page(self.out / "renamed-local.md")
        self.page(self.out / "old-continuation.md", continues="missing-original")
        public_before = published.read_bytes()
        snapshot = D.privacy_snapshot()
        self.assertTrue(D.no_llm_of_pages([], self.record(), snapshot))
        D.carry_privacy(snapshot)
        self.assertTrue(all(S.doc_meta(path.read_text())[2] for path in self.out.glob("*.md")))
        self.assertEqual(published.read_bytes(), public_before)
        docs = [{"title": "Human supplied continuation", "doc_type": "decision", "why_captured": "reviewed",
                 "tags": [], "body": "Already reviewed, not generated by a model."}]
        made = D.write(self.record(), docs, {}, continues="missing-original")
        self.assertTrue(S.doc_meta((self.out / (made[0][0] + ".md")).read_text())[2])
        published.unlink()
        self.assertTrue(D.no_llm_of_pages([], self.record()))

    def test_restart_and_missing_marker_are_gated_before_any_model_call(self):
        self.page(self.bundle / "human-renamed.md", blocked=True, published=True)
        for restart in (False, True):
            with self.subTest(restart=restart):
                result, model = self.run_main(self.record(), restart=restart)
                self.assertEqual(result, 0)
                model.assert_not_called()
                self.assertFalse(list(self.done.iterdir()))

    def test_session_agent_namespace_and_body_provenance_do_not_cross_gate(self):
        self.page(self.bundle / "private.md", agent="codex", blocked=True, published=True)
        (self.bundle / "prose.md").write_text("---\nno_llm: true\n---\nsources:\n  - resource: claude-session://session\n")
        self.assertFalse(D.no_llm_of_pages([], self.record()))
        self.assertTrue(D.no_llm_of_pages([], self.record("codex")))

    def test_existing_local_flag_stays_true_and_protects_renamed_pages(self):
        original = self.out / "renamed.md"
        self.page(original, blocked=True)
        before = original.read_bytes()
        self.assertEqual(self.run_main(self.record())[0], 0)
        self.assertEqual(original.read_bytes(), before)

    def codex_fixture(self):
        path = self.root / "rollout-fixture.jsonl"
        rows = [{"type": "session_meta", "payload": {"id": "session", "cwd": "/fixture"}}]

        def add(stamp, kind, payload):
            rows.append({"timestamp": stamp, "type": kind, "payload": payload})

        def message(stamp, body, role="user"):
            add(stamp, "response_item", {"type": "message", "role": role,
                                        "content": [{"type": "input_text" if role == "user" else "output_text", "text": body}]})

        message("2020-01-01T00:00:00Z", "BOUNDARY_CANARY already reviewed")
        message("2019-12-31T19:00:00-05:00", "OFFSET_BOUNDARY_CANARY")
        message(None, "UNKNOWN_TIMESTAMP_CANARY")
        message("2020-01-01T12:00:00Z", "<INSTRUCTIONS>INJECTED_CANARY</INSTRUCTIONS>\nReal follow-up " + self.secret)
        message("2020-01-02T00:00:00Z", "Final decision", "assistant")
        add("2020-01-02T00:00:00Z", "event_msg", {"type": "agent_message", "message": "Final decision"})
        add("2020-01-01T23:00:00Z", "event_msg", {"type": "user_message", "message": "Event-only user follow-up"})
        message("2020-01-01T20:00:00Z", "DEVELOPER_CANARY", "developer")
        add("2020-01-01T20:00:00Z", "response_item", {"type": "function_call_output", "output": "TOOL_CANARY"})
        message("2020-01-02T00:00:01Z", "UNCOLLECTED_CANARY")
        path.write_text("\n".join(json.dumps(row) for row in rows) + "\n")
