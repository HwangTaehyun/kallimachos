    def test_codex_and_hermes_skip_advance_markers_and_zero_calls_on_rerun(self):
        for fixture in (self.codex_fixture, self.hermes_fixture):
            rec = fixture()
            marker = self.done / (rec["agent"] + "-session")
            marker.write_text(json.dumps({"last_ts": "2020-01-01T00:00:00Z", "pages": ["original-page"]}))
            result, model = self.run_main(rec)
            self.assertEqual(result, 0)
            model.assert_called_once()
            self.assertNotIn("CANARY", model.call_args.args[0])
            self.assertEqual(json.loads(marker.read_text()), {"last_ts": rec["last_ts"], "pages": ["original-page"]})
            result, model = self.run_main(rec)
            self.assertEqual(result, 0)
            model.assert_not_called()

    def test_codex_and_hermes_success_append_pages_with_original_provenance(self):
        reply = "<<<DOC>>>\ntitle: New conclusion\ndoc_type: decision\nwhy_captured: Review\ntags: fixture\n---\nA new reviewed decision.\n<<<END>>>"
        for fixture in (self.codex_fixture, self.hermes_fixture):
            rec = fixture()
            marker = self.done / (rec["agent"] + "-session")
            marker.write_text(json.dumps({"last_ts": "2020-01-01T00:00:00Z", "pages": ["original-page"]}))
            result, model = self.run_main(rec, reply)
            self.assertEqual(result, 0)
